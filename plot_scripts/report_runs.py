"""
Inventory of the time-evolution runs with the current coefficients, for the data report of the notes (chapter
"Data computed"): one row per (state, noise channel, method, random-c seed) with the sizes L and the γ values that
exist on disk, whether in data/used_data or in data/used_data/lean (the same run in both counts once).

  method   exact (`states`), diffusive (`states_traj`), jump (`states_traj --unravel jump`, traj-seeds pooled)
  γ        only γ = 0 and γ ≥ 0.01 are listed (notes_layout.GAMMA_MIN); the number of omitted smaller γ is printed

Also prints the `single_flip` runs (L, phases × kicked sites, τ range) found in the same directories.

Input:  data/used_data (or the directory given as the first argument)
Output: a LaTeX table on stdout (pasted into latex/sections/data.tex)
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

import pandas as pd

from notes_layout import keep_gamma

DIR = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "data" / "used_data"
NAME = re.compile(r"states_(traj_)?(minus-x|neel-x|neel)_L(\d+)_g([0-9.]+?)"
                  r"(?:_ch(x|y|dep|decay|thermal)(?:_n1)?)?(?:_seed(\d+))?(_jump)?(?:_s\d+)?\.csv$")
STATE = {"minus-x": "scar", "neel-x": "$x$-N\\'eel", "neel": "$z$-N\\'eel"}
CHANNEL = {"z": "$\\sigma^z$", "x": "$\\sigma^x$", "y": "$\\sigma^y$", "dep": "depol.", "decay": "decay",
           "thermal": "thermal"}
METHOD = {"exact": "exact", "traj": "diffusive", "jump": "jump"}


def compact(values):
    """8 9 10 11 12 → 8–12; even runs 12 14 16 → 12, 14, 16."""
    values = sorted(values)
    out, i = [], 0
    while i < len(values):
        j = i
        while j + 1 < len(values) and values[j + 1] == values[j] + 1:
            j += 1
        out.append(f"{values[i]}--{values[j]}" if j - i >= 2 else ", ".join(map(str, values[i:j + 1])))
        i = j + 1
    return ", ".join(out)


def gammas(values):
    return ", ".join(f"{g:g}" for g in sorted(values))


def main():
    runs = defaultdict(lambda: defaultdict(set))  # (state, channel, method, seed) -> L -> {γ}
    omitted = set()
    for f in list(DIR.glob("states_*_L*_g*.csv")) + list((DIR / "lean").glob("states_*_L*_g*.csv")):
        m = NAME.match(f.name)
        if m is None or f.name.startswith(("states_obs", "states_traj_ent")):
            continue
        traj, state, l, g, ch, seed, jump = m.groups()
        g = float(g)
        method = "jump" if jump else "traj" if traj else "exact"
        if not keep_gamma(g):
            omitted.add((state, method, int(l), g))
            continue
        runs[state, ch or "z", method, int(seed or 1)][int(l)].add(g)
    rows = []
    for (state, ch, method, seed), by_l in runs.items():
        groups = defaultdict(list)  # same γ set → one row with every L that has it
        for l, gs in by_l.items():
            groups[frozenset(gs)].append(l)
        for gs, ls in groups.items():
            rows.append((list(STATE).index(state), list(CHANNEL).index(ch), list(METHOD).index(method), seed,
                         min(ls), STATE[state], CHANNEL[ch], METHOD[method], seed, compact(ls), gammas(gs)))
    rows.sort()
    print("% generated by plot_scripts/report_runs.py")
    print("\\begin{longtable}{lllcp{2.6cm}p{6.2cm}}")
    print("\\toprule state & noise & method & seed & $L$ & $\\gamma$ \\\\ \\midrule \\endhead")
    for r in rows:
        print(" & ".join(map(str, r[5:])) + " \\\\")
    print("\\bottomrule\n\\end{longtable}")
    print(f"% omitted: {len(omitted)} runs with 0 < γ < 0.01", file=sys.stderr)

    flips = []
    for f in sorted(list(DIR.glob("single_flip_L*.csv")) + list((DIR / "lean").glob("single_flip_L*.csv"))):
        if "_ent" in f.name:
            continue
        d = pd.read_csv(f, usecols=["L", "m", "k", "tau"])
        flips.append((f.parent.name, f.name, int(d["L"].iloc[0]), d["m"].nunique(), d["k"].nunique(), d["tau"].max()))
    print("% single_flip: dir, file, L, phases, kicked sites, tau_max", file=sys.stderr)
    for row in flips:
        print("%", *row, file=sys.stderr)


if __name__ == "__main__":
    main()
